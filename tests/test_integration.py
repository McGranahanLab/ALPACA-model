@pytest.mark.integration
def test_infeasible_segment(tmp_path, repo_root, run_alpaca, update_golden):
    """The nominated segment is simulated infeasible; the other segment is solved normally."""
    infeasible_segment = "1_762496_28527452"
    input_dir = repo_root / "tests" / "infeasible_segment" / "input" / TUMOUR_ID
    run_alpaca(
        "run",
        "--input_tumour_directory", str(input_dir),
        "--output_directory", str(tmp_path),
        "--debug",
        "--simulate_infeasibility", infeasible_segment,
        "--plot_output_mode", "none",
        *_PYOMO_SCIP,
    )

    output_csv = tmp_path / f"ALPACA_output_{TUMOUR_ID}.csv"
    assert output_csv.exists()

    df = pd.read_csv(output_csv)
    assert infeasible_segment not in df["segment"].values, (
        f"Segment {infeasible_segment!r} was simulated infeasible "
        "but appeared in the output."
    )

    golden_dir = _golden(repo_root, "infeasible_segment")
    assert_csv_matches_golden(
        output_csv,
        golden_dir / f"ALPACA_output_{TUMOUR_ID}.csv",
        ignore_cols=VOLATILE_COLS,
        update=update_golden,
    )


