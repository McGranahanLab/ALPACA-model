"""Integration tests for the alpaca CLI.

Each test invokes ``alpaca run`` via subprocess, writes output to pytest's
``tmp_path``, and compares key CSV files against committed golden files stored
in ``tests/<scenario>/expected/``.

Golden files are regenerated by running::

    pytest tests/test_integration.py --update-golden

Columns that vary across runs (timestamps etc.) are excluded from
comparisons via the ``VOLATILE_COLS`` / ``GUROBI_VOLATILE_COLS`` constants
defined in conftest.py.
"""

import shutil

import pandas as pd
import pytest


from golden_utils import VOLATILE_COLS, assert_csv_matches_golden

TUMOUR_ID = "LTX0000-Tumour1"

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

_PYOMO_GLPK = ("--solver", "pyomo", "--pyomo_solver", "glpk")
_PYOMO_SCIP = ("--solver", "pyomo", "--pyomo_solver", "scip")
_PYOMO_GUROBI = ("--solver", "pyomo", "--pyomo_solver", "gurobi")


def _golden(repo_root, scenario):
    return repo_root / "tests" / scenario / "expected"


# ---------------------------------------------------------------------------
# Core alpaca run tests
# ---------------------------------------------------------------------------


@pytest.mark.integration
def test_correct_input(tmp_path, repo_root, run_alpaca, update_golden):
    input_dir = repo_root / "examples" / "example_cohort" / "input" / TUMOUR_ID
    run_alpaca(
        "run",
        "--input_tumour_directory", str(input_dir),
        "--output_directory", str(tmp_path),
        "--debug",
        *_PYOMO_GLPK,
    )

    golden_dir = _golden(repo_root, "correct_input")
    assert_csv_matches_golden(
        tmp_path / f"ALPACA_output_{TUMOUR_ID}.csv",
        golden_dir / f"ALPACA_output_{TUMOUR_ID}.csv",
        ignore_cols=VOLATILE_COLS,
        update=update_golden,
    )
    assert_csv_matches_golden(
        tmp_path / "cn_change_to_ancestor.csv",
        golden_dir / "cn_change_to_ancestor.csv",
        ignore_cols=VOLATILE_COLS,
        update=update_golden,
    )


